    for token in sorted(tf.themed):
        light, dark = tf.color(token)
        w(f"    static let {color_name(token)} = {swift_pair(light, dark)}")
    w("}")
    w("")

    def scalar_group(enum_name: str, group: str, names: dict[str, str], kind: str, swift_type: str) -> None:
        w(f"enum {enum_name} {{")
        for token_name, value in tf.plain(group).items():
            swift_name = names.get(token_name)
            if swift_name is None:
                fail(f"{group}: no Swift name for {token_name!r}")
            if kind == "px":
                rendered = f"{px(value, token_name):g}"
            else:
                rendered = f"{duration_seconds(value, token_name):g}"
            w(f"    static let {swift_name}: {swift_type} = {rendered}")
        w("}")
        w("")

    scalar_group("JidrSpace", "spacing", SPACE_NAMES, "px", "CGFloat")
    scalar_group("JidrRadius", "radius", RADIUS_NAMES, "px", "CGFloat")
    scalar_group("JidrBorder", "border", BORDER_NAMES, "px", "CGFloat")
    scalar_group("JidrSize", "size", SIZE_NAMES, "px", "CGFloat")
    scalar_group("JidrFrame", "frame", FRAME_NAMES, "px", "CGFloat")
    scalar_group("JidrDensity", "density", DENSITY_NAMES, "px", "CGFloat")
    scalar_group("JidrLayout", "layout", LAYOUT_NAMES, "px", "CGFloat")

    w("/// Base durations in seconds (the token file writes ms).")
    w("enum JidrDuration {")
    for token_name, value in tf.plain("duration").items():
        if not token_name.startswith("duration-"):
            continue
        swift_name = DURATION_NAMES.get(token_name)
        if swift_name is None:
            fail(f"duration: no Swift name for {token_name!r}")
        w(f"    static let {swift_name}: TimeInterval = {duration_seconds(value, token_name):g}")
    w("}")
    w("")
    w("/// Motion distances in points (a sheet rises/drops this far).")
    w("enum JidrMotionDistance {")
    for token_name, value in tf.plain("duration").items():
        if not token_name.endswith("-distance"):
            continue
        stem = token_name[: -len("-distance")]
        if stem.startswith("motion-"):
            stem = stem[len("motion-"):]
        w(f"    static let {camel(stem)} = {px(value, token_name):g}")
    w("}")
    w("")
    w("/// Cubic-bezier curves, from the shared design-token easing values.")
    w("enum JidrEasing {")
    for token_name, value in tf.plain("easing").items():
        match = re.fullmatch(r"cubic-bezier\(([^)]*)\)", value)
        if not match:
            fail(f"easing {token_name}: unsupported value {value!r}")
        xs = [float(part.strip()) for part in match.group(1).split(",")]
        if len(xs) != 4:
            fail(f"easing {token_name}: expected 4 control points")
        w(f"    static let {camel(token_name)} = JidrCurve({xs[0]:g}, {xs[1]:g}, {xs[2]:g}, {xs[3]:g})")
    w("}")
    w("")
    w("struct JidrCurve {")
    w("    let x1: Double; let y1: Double; let x2: Double; let y2: Double")
    w("    init(_ x1: Double, _ y1: Double, _ x2: Double, _ y2: Double) {")
    w("        self.x1 = x1; self.y1 = y1; self.x2 = x2; self.y2 = y2")
    w("    }")
    w("}")
    w("")
    w("/// Motion pairs: normal duration + the Reduce Motion duration from")
    w("/// docs/design/system/components/bundle.css, and the curve between them.")
    w("enum JidrMotion {")
    motion = tf.plain("duration")
    easings = tf.plain("easing")
    for token_name in sorted(motion):
        if not token_name.endswith("-duration") or not token_name.startswith("motion-"):
            continue
        stem = token_name[: -len("-duration")]
        stem = stem[len("motion-"):]
        duration = duration_seconds(motion[token_name], token_name)
        reduced_raw = reduced.get(token_name)
        reduced_s = duration_seconds(reduced_raw, token_name) if reduced_raw else duration
        curve_name = f"motion-{stem}-easing"
        curve_value = easings.get(curve_name)
        if curve_value is None:
            fail(f"motion {stem}: missing {curve_name}")
        match = re.fullmatch(r"cubic-bezier\(([^)]*)\)", curve_value)
        if not match:
            fail(f"easing {curve_name}: unsupported value")
        xs = [float(part.strip()) for part in match.group(1).split(",")]
        distance_name = f"motion-{stem}-distance"
        distance = 0.0
        if distance_name in motion:
            distance = px(motion[distance_name], distance_name)
        w(f"    static let {camel(stem)} = JidrMotionPair(duration: {duration:g}, reduced: {reduced_s:g},")
        w(f"        curve: JidrCurve({xs[0]:g}, {xs[1]:g}, {xs[2]:g}, {xs[3]:g}), distance: {distance:g})")
    w("}")
    w("")
    w("struct JidrMotionPair {")
    w("    let duration: TimeInterval")
    w("    let reduced: TimeInterval")
    w("    let curve: JidrCurve")
    w("    let distance: CGFloat")
    w("")
    w("    func animation(reduceMotion: Bool) -> Animation? {")
    w("        let seconds = reduceMotion ? reduced : duration")
    w("        guard seconds > 0 else { return nil }")
    w("        return .timingCurve(curve.x1, curve.y1, curve.x2, curve.y2, duration: seconds)")
    w("    }")
    w("}")
    w("")

    # Shadows
    shadows = tf.themed_tokens("shadow")
    w("/// One shadow per element. Dark elevation")
    w("/// is a surface tint plus border instead, so the dark shadow colour is clear.")
    w("enum JidrShadow {")
    for token_name in sorted(shadows):
        sfx = token_name[len("elevation-"):-len("-shadow")] if token_name.startswith("elevation-") else token_name
        dark_raw, light_raw = shadows[token_name]
        _, _, dark_blur, _, dark_color = parse_shadow(dark_raw, token_name)
        _, _, light_blur, _, light_color = parse_shadow(light_raw, token_name)
        dx, dy, blur, spread, _ = parse_shadow(light_raw, token_name)
        w(f"    static let elevation{sfx} = JidrShadowStyle(")
        w(f"        light: {swift_pair(light_color, dark_color)},")
        w(f"        x: {dx:g}, y: {dy:g}, blur: {light_blur:g}, spread: {spread:g})")
    w("}")
    w("")
    w("struct JidrShadowStyle {")
    w("    let color: JidrColorPair")
    w("    let x: CGFloat; let y: CGFloat; let blur: CGFloat; let spread: CGFloat")
    w("    init(light: JidrColorPair, x: CGFloat, y: CGFloat, blur: CGFloat, spread: CGFloat) {")
    w("        self.color = light; self.x = x; self.y = y; self.blur = blur; self.spread = spread")
    w("    }")
    w("}")
    w("")

    # Typography
    styles = tf.typography()
    w("// MARK: - Type")
    w("")
    w("/// Typography roles from `type.groups` (App, Arabic, Landing). The token")
    w("/// families are Geist / Geist Mono / Noto Kufi Arabic; `font` resolves the")
    w("/// bundled face when the app registered it and falls back to the system font")
    w("/// otherwise (see WbFontResolver). Sizes, weights, line heights and tracking")
    w("/// are exact token values.")
    w("enum JidrType {")
    for style_name, family, style in styles:
        size = px(style["fontSize"], style_name)
        line = px(style["lineHeight"], style_name)
        tracking = px(style["letterSpacing"], style_name) if "letterSpacing" in style else 0.0
        weight = int(style.get("fontWeight", 400))
        weight_name = WEIGHTS.get(weight)
        if weight_name is None:
            fail(f"type {style_name}: unknown fontWeight {weight}")
        family_case = {"mono": ".mono", "arabic": ".arabic"}.get(family, ".ui")
        w(f"    static let {camel(style_name)} = JidrTextStyle(size: {size:g}, weight: .{weight_name},")
        w(f"        lineHeight: {line:g}, tracking: {tracking:g}, family: {family_case})")
    w("}")
    w("")
    w("struct JidrTextStyle {")
    w("    let size: CGFloat")
    w("    let weight: Font.Weight")
    w("    let lineHeight: CGFloat")
    w("    let tracking: CGFloat")
    w("    let family: JidrFontFamily")
    w("")
    w("    /// The bundled face for this role, or the system font when the app did")
    w("    /// not register the font files (see WbFontResolver).")
    w("    var font: Font { WbFontResolver.font(family: family, weight: weight, size: size) }")
    w("")
    w("    /// Extra line spacing to approximate the token line height (SwiftUI has")
    w("    /// no direct line-height control; 1.2x the size is the system default).")
    w("    var lineSpacing: CGFloat { max(0, lineHeight - size * 1.2) }")
    w("")
    w("    func weighted(_ weight: Font.Weight) -> JidrTextStyle {")
    w("        JidrTextStyle(size: size, weight: weight, lineHeight: lineHeight,")
    w("                      tracking: tracking, family: family)")
    w("    }")
    w("}")
    w("")
    return "\n".join(out)


