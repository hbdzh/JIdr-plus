    for swift_name in ("zero", "xxs", "xs", "sm", "md", "lg", "xl", "xxl", "xxxl", "xxxxl", "xxxxxl"):
        w(f"    static let {swift_name} = JidrSpace.{swift_name}")
    w("}")
    w("")
    w("/// Radii: pill for status, md for controls and rows, lg for cards, xl for sheets.")
    w("enum WbRadius {")
    for swift_name in ("xs", "sm", "md", "lg", "xl", "pill"):
        w(f"    static let {swift_name} = JidrRadius.{swift_name}")
    w("}")
    w("")
    w("enum WbBorder {")
    for swift_name in ("hairline", "emphasis", "focus", "focusOffset"):
        w(f"    static let {swift_name} = JidrBorder.{swift_name}")
    w("}")
    w("")
    w("/// Icon and control sizes (the Semantic `WbIcon` enum below holds the glyph names).")
