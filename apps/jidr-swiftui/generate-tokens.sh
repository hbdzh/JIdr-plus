EXACT_LUCIDE_FALLBACK = """\
// MARK: - Exact-Lucide fallback (documented, not enabled in M3)
//
// SF Symbols above are used for native rendering; Lucide SVGs are shared with the demo.
// If a glyph must match Lucide exactly (the design system treats badge-check,
// key-round, circle-help and flask-conical as spec shapes), generate SwiftUI
// Paths from assets/lucide/<name>.svg instead of adding a runtime
// SVG dependency:
//
//   1. Parse the 24x24 viewBox and its <path d="..."/> children (plus
//      circle/rect/line/polyline for completeness).
//   2. Support the SVG path subset M/m L/l H/h V/v C/c S/s Q/q T/t Z/z: moveTo,
//      addLine, addCurve, addQuadCurve. `A/a` arcs need endpoint-to-centre
//      parameterisation (then Path.addArc) or a cubic approximation; icons whose
//      paths use arcs are listed by the parser and skipped until that lands.
//   3. Emit one `static func <name>(in rect: CGRect) -> Path` per icon (scale
//      24 -> rect) into a generated Sources/IconPaths.swift.
//   4. Draw with `.stroke(style: StrokeStyle(lineWidth: WbIconSize.iconStroke,
//      lineCap: .round, lineJoin: .round))` and tint with `.foregroundStyle`.
//
// Trade-offs, which is why it is opt-in: ~100 generated lines per icon (the
// Lucide set is 104 icons), a path parser to maintain, re-generation whenever
// the icon set changes, and it loses SF Symbol weights/rendering modes and the
// free accessibility labels. The SF Symbol mapping is smaller, system-rendered
// and localised. Use the fallback only where visual mismatch is a real defect.
//
// `generate-tokens.sh --icon-snippet <svg>` prints the minimal snippet for
// simple icons (M/L/H/V/C/Q/T/Z, no arcs) as a starting point.
"""


