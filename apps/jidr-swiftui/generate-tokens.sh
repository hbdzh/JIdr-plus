def strip_jidr(name: str) -> str:
    return name[len("jidr-"):] if name.startswith("jidr-") else name


def px(value: str, where: str) -> float:
    if not isinstance(value, str) or not value.endswith("px"):
        fail(f"{where}: expected a px value, got {value!r}")
    try:
        return float(value[:-2])
    except ValueError:
        fail(f"{where}: bad px value {value!r}")


def duration_seconds(value: str, where: str) -> float:
    if not isinstance(value, str) or not value.endswith("ms"):
        fail(f"{where}: expected an ms value, got {value!r}")
    return float(value[:-2]) / 1000.0


def parse_hex(value: str, where: str) -> ColorValue:
    if not isinstance(value, str) or not value.startswith("#"):
        fail(f"{where}: expected #rrggbb/#rrggbbaa, got {value!r}")
    hex_part = value[1:]
    if len(hex_part) not in (6, 8) or any(c not in "0123456789abcdefABCDEF" for c in hex_part):
        fail(f"{where}: not a colour: {value!r}")
    rgb = int(hex_part[:6], 16)
    alpha = int(hex_part[6:8], 16) / 255.0 if len(hex_part) == 8 else 1.0
    return ColorValue(rgb, alpha)


def parse_shadow(value: str, where: str) -> tuple[float, float, float, float, ColorValue]:
    parts = value.split()
    if len(parts) != 5:
        fail(f"{where}: bad shadow {value!r}")
    x = px(parts[0], where)
    y = px(parts[1], where)
    blur = px(parts[2], where)
    spread = px(parts[3], where)
    color = parse_hex(parts[4], where)
    return x, y, blur, spread, color


class TokenFile:
    def __init__(self, data: dict):
        self.data = data
        self.themed: dict[str, tuple[str, str]] = {}
        self.resolved: dict[str, tuple[str, str]] = {}
        colors = self.group("color")["tokens"]
        for token in colors:
            value = token.get("value")
            if not isinstance(value, dict) or "dark" not in value or "light" not in value:
                fail(f"colour token {token.get('name')}: expected dark/light pairs")
            self.themed[token["name"]] = (value["dark"], value["light"])
        for name in self.themed:
            self.resolved[name] = (self._resolve(name, True), self._resolve(name, False))

    def group(self, name: str) -> dict:
        group = self.data.get(name)
        if not isinstance(group, dict) or "tokens" not in group:
            fail(f"tokens.json: missing group {name!r}")
        return group

    def _resolve(self, name: str, dark: bool) -> str:
        value = self.themed[name][0 if dark else 1]
        for _ in range(8):
            match = re.fullmatch(r"\{(.+)\}", value)
            if not match:
                return value
            target = match.group(1)
            if target not in self.themed:
                fail(f"colour token {name}: unknown alias {target!r}")
            value = self.themed[target][0 if dark else 1]
        fail(f"colour token {name}: alias chain too long")

    def color(self, token: str) -> tuple[ColorValue, ColorValue]:
        if token not in self.resolved:
            fail(f"unknown colour token {token!r}")
        dark, light = self.resolved[token]
        return parse_hex(light, token), parse_hex(dark, token)

    def plain(self, group: str) -> dict[str, str]:
        out: dict[str, str] = {}
        for token in self.group(group)["tokens"]:
            name = strip_jidr(token["name"])
            if name in out:
                fail(f"{group}: duplicate token {name!r}")
            value = token.get("value")
            if not isinstance(value, str):
                fail(f"{group} token {name}: expected a string value")
            out[name] = value
        return out

    def themed_tokens(self, group: str) -> dict[str, tuple[str, str]]:
        out: dict[str, tuple[str, str]] = {}
        for token in self.group(group)["tokens"]:
            value = token.get("value")
            if not isinstance(value, dict):
                fail(f"{group} token {token.get('name')}: expected dark/light values")
            out[strip_jidr(token["name"])] = (value["dark"], value["light"])
        return out

    def typography(self) -> list[tuple[str, str, dict]]:
        type_group = self.data.get("type")
        if not isinstance(type_group, dict):
            fail("tokens.json: missing type group")
        families = type_group.get("families")
        if not isinstance(families, dict):
            fail("tokens.json: missing type.families")
        styles: list[tuple[str, str, dict]] = []
        for group in type_group.get("groups", []):
            family = group.get("family", "ui")
            for style in group.get("styles", []):
                name = strip_jidr(style["name"])
                if name.startswith("type-"):
                    name = name[len("type-"):]
                styles.append((name, style.get("family", family), style))
        return styles


def reduced_motion(css_path: Path) -> dict[str, str]:
    if not css_path.exists():
        return {}
    css = css_path.read_text()
    match = re.search(r"prefers-reduced-motion:\s*reduce\)\s*\{(.*?)\n\}", css, re.S)
    if not match:
        return {}
    overrides: dict[str, str] = {}
    for line in match.group(1).splitlines():
        line = line.strip().rstrip(";")
        if ":" not in line:
            continue
        key, value = line.split(":", 1)
        key = key.strip()
        if key.startswith("--jidr-"):
            overrides[key[len("--jidr-"):]] = value.strip()
    return overrides


