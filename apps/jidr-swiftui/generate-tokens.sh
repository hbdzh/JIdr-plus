    for swift_name in ("iconSm", "iconMd", "iconLg", "iconStroke", "controlHeightSm", "controlHeightMd", "controlHeightLg"):
        w(f"    static let {swift_name} = JidrSize.{swift_name}")
    w("}")
    w("")
    w("/// Window, panel and breakpoint sizes from `layout` (design rules, not view state).")
    w("enum WbLayout {")
    for swift_name in ("windowLauncherMinWidth", "windowLauncherMinHeight", "windowTitlebarHeight",
                       "windowSidebarWidth", "windowInspectorWidth", "windowDeviceToolbarWidth",
                       "windowDeviceWidgetPanelWidth", "windowDeviceMinScreenHeight",
                       "breakpointSm", "breakpointMd", "breakpointLg", "breakpointXl"):
        w(f"    static let {swift_name} = JidrLayout.{swift_name}")
    w("}")
    w("")
    w(render_typography_helpers())
    w(font_face_code())
    w("// MARK: - Motion")
    w("")
    w("/// Motion pairs with their Reduce Motion fallback (bundle.css overrides are")
    w("/// generated into the raw layer). Pass the current Reduce Motion setting.")
    w("enum WbMotion {")
    for swift_name in ("hover", "popover", "sheet", "panel", "status", "progress", "rootSuccess", "skeleton", "spinner"):
        w(f"    static let {swift_name} = JidrMotion.{swift_name}")
    w("    /// Palette scroll-to-selection: hover-speed, no distance.")
    w("    static let scroll = JidrMotion.hover")
    w("}")
    w("")
    w("enum WbDuration {")
    for swift_name in ("instant", "fast", "base", "slow", "deliberate", "spin", "shimmer"):
        w(f"    static let {swift_name} = JidrDuration.{swift_name}")
    w("}")
    w("")
    w("// MARK: - Elevation")
    w("")
    w("enum WbShadow {")
    w("    static let ground = JidrShadow.elevation0")
    w("    static let card = JidrShadow.elevation1")
    w("    static let popover = JidrShadow.elevation2")
    w("    static let sheet = JidrShadow.elevation3")
    w("}")
    w("")
    w("extension View {")
    w("    /// Applies one token shadow. Dark tokens are clear (elevation is the")
    w("    /// surface tint plus border there), so the same call is correct in both")
    w("    /// themes; pair it with `WbColor.borderDefault` where a border is needed.")
    w("    func wbShadow(_ shadow: JidrShadowStyle) -> some View {")
    w("        self.shadow(color: shadow.color.color,")
    w("                    radius: shadow.blur / 2, x: shadow.x, y: shadow.y)")
    w("    }")
    w("}")
    w("")
    w("// MARK: - Icons")
    w("")
    w("/// SF Symbol names by meaning. Generated from the semantic table in")
    w("/// generate-tokens.sh (see Center/DesignTokens.swift for the Lucide mapping);")
    w("/// views must use these instead of raw system image names.")
    w("enum WbIcon {")
    for name, symbol, lucide, usage in ICON_SYMBOLS:
        provenance = f"Lucide {lucide}" if lucide not in ("", "SF-native") else "SF-native"
        w(f"    /// {usage} ({symbol}; {provenance})")
        w(f'    static let {name} = "{symbol}"')
    w("}")
    w("")
    return "\n".join(out)


