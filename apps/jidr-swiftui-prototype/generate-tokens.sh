    w("enum JidrMotion {")
    motion = tf.plain("duration")
    easings = tf.plain("easing")
    for token_name in sorted(motion):
        if not token_name.endswith("-duration") or not token_name.startswith("motion-"):
            continue
        stem = token_name[: -len("-duration")]
        stem = stem[len("motion-"):]
        duration = duration_seconds(motion[token_name], token_name)
        reduced_raw = reduced.get(token_name)
        reduced_s = duration_seconds(reduced_raw, token_name) if reduced_raw else duration
        curve_name = f"motion-{stem}-easing"
        curve_value = easings.get(curve_name)
        if curve_value is None:
            fail(f"motion {stem}: missing {curve_name}")
        match = re.fullmatch(r"cubic-bezier\(([^)]*)\)", curve_value)
        if not match:
            fail(f"easing {curve_name}: unsupported value")
        xs = [float(part.strip()) for part in match.group(1).split(",")]
        distance_name = f"motion-{stem}-distance"
        distance = 0.0
        if distance_name in motion:
            distance = px(motion[distance_name], distance_name)
        w(f"    static let {camel(stem)} = JidrMotionPair(duration: {duration:g}, reduced: {reduced_s:g},")
        w(f"        curve: JidrCurve({xs[0]:g}, {xs[1]:g}, {xs[2]:g}, {xs[3]:g}), distance: {distance:g})")
    w("}")
    w("")
    w("struct JidrMotionPair {")
    w("    let duration: TimeInterval")
    w("    let reduced: TimeInterval")
    w("    let curve: JidrCurve")
    w("    let distance: CGFloat")
    w("")
    w("    func animation(reduceMotion: Bool) -> Animation? {")
    w("        let seconds = reduceMotion ? reduced : duration")
    w("        guard seconds > 0 else { return nil }")
    w("        return .timingCurve(curve.x1, curve.y1, curve.x2, curve.y2, duration: seconds)")
    w("    }")
    w("}")
    w("")

    # Shadows
    shadows = tf.themed_tokens("shadow")
    w("/// One shadow per element (Slint draws a single drop shadow). Dark elevation")
    w("/// is a surface tint plus border instead, so the dark shadow colour is clear.")
    w("enum JidrShadow {")
    for token_name in sorted(shadows):
        sfx = token_name[len("elevation-"):-len("-shadow")] if token_name.startswith("elevation-") else token_name
        dark_raw, light_raw = shadows[token_name]
        _, _, dark_blur, _, dark_color = parse_shadow(dark_raw, token_name)
        _, _, light_blur, _, light_color = parse_shadow(light_raw, token_name)
        dx, dy, blur, spread, _ = parse_shadow(light_raw, token_name)
        w(f"    static let elevation{sfx} = JidrShadowStyle(")
        w(f"        light: {swift_pair(light_color, dark_color)},")
        w(f"        x: {dx:g}, y: {dy:g}, blur: {light_blur:g}, spread: {spread:g})")
    w("}")
    w("")
    w("struct JidrShadowStyle {")
    w("    let color: JidrColorPair")
    w("    let x: CGFloat; let y: CGFloat; let blur: CGFloat; let spread: CGFloat")
    w("    init(light: JidrColorPair, x: CGFloat, y: CGFloat, blur: CGFloat, spread: CGFloat) {")
    w("        self.color = light; self.x = x; self.y = y; self.blur = blur; self.spread = spread")
    w("    }")
    w("}")
    w("")

    # Typography
    styles = tf.typography()
    w("// MARK: - Type")
    w("")
    w("/// Typography roles from `type.groups` (App, Arabic, Landing). The SwiftUI")
    w("/// prototype does not bundle Geist/Noto Kufi yet, so `font` renders with the")
    w("/// system font; `mono` roles use the monospaced design. The token sizes,")
    w("/// weights, line heights and tracking are exact.")
    w("enum JidrType {")
    for style_name, family, style in styles:
        size = px(style["fontSize"], style_name)
        line = px(style["lineHeight"], style_name)
        tracking = px(style["letterSpacing"], style_name) if "letterSpacing" in style else 0.0
        weight = int(style.get("fontWeight", 400))
        weight_name = WEIGHTS.get(weight)
        if weight_name is None:
            fail(f"type {style_name}: unknown fontWeight {weight}")
        is_mono = family == "mono"
        w(f"    static let {camel(style_name)} = JidrTextStyle(size: {size:g}, weight: .{weight_name},")
        w(f"        lineHeight: {line:g}, tracking: {tracking:g}, mono: {str(is_mono).lower()})")
    w("}")
    w("")
    w("struct JidrTextStyle {")
    w("    let size: CGFloat")
    w("    let weight: Font.Weight")
    w("    let lineHeight: CGFloat")
    w("    let tracking: CGFloat")
    w("    let mono: Bool")
    w("")
    w("    var font: Font {")
    w("        mono ? .system(size: size, weight: weight, design: .monospaced)")
    w("             : .system(size: size, weight: weight)")
    w("    }")
    w("")
    w("    /// Extra line spacing to approximate the token line height (SwiftUI has")
    w("    /// no direct line-height control; 1.2x the size is the system default).")
    w("    var lineSpacing: CGFloat { max(0, lineHeight - size * 1.2) }")
    w("")
    w("    func weighted(_ weight: Font.Weight) -> JidrTextStyle {")
    w("        JidrTextStyle(size: size, weight: weight, lineHeight: lineHeight,")
    w("                      tracking: tracking, mono: mono)")
    w("    }")
    w("}")
    w("")
    families = tf.data["type"].get("families", {})
    w("/// The token font stacks (CSS order). Bundling the font files is a later")
    w("/// line; these strings are kept so the mapping to D41 stays visible.")
    w("enum JidrFontFamily {")
    for key in ("ui", "mono", "arabic"):
        stack = families.get(key, "")
        first = stack.split(",")[0].strip().strip('"')
        w(f"    static let {key} = \"{first}\"")
    w("}")
    w("")
    return "\n".join(out)


