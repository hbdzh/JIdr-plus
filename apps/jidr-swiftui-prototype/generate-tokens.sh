    w("// `jidr-space-md` -> JidrSpace.md. A leading `color-` is dropped, as in Slint (D41).")
    w("")
    w("import AppKit")
    w("import SwiftUI")
    w("")
    w("// MARK: - Colour plumbing")
    w("")
    w("/// A token colour that carries both themes. `color` resolves through the")
    w("/// current `NSAppearance`, so a view drawn in light or dark (or forced with")
    w("/// `.preferredColorScheme`) picks the matching value without per-view code.")
    w("struct JidrColorPair {")
    w("    let lightRGB: UInt32")
    w("    let lightAlpha: Double")
    w("    let darkRGB: UInt32")
    w("    let darkAlpha: Double")
    w("")
    w("    init(light: UInt32, dark: UInt32) {")
    w("        self.init(light: light, lightAlpha: 1, dark: dark, darkAlpha: 1)")
    w("    }")
    w("")
    w("    init(light: UInt32, lightAlpha: Double, dark: UInt32, darkAlpha: Double) {")
    w("        self.lightRGB = light; self.lightAlpha = lightAlpha")
    w("        self.darkRGB = dark; self.darkAlpha = darkAlpha")
    w("    }")
    w("")
    w("    var light: Color { wbTokenColor(lightRGB, lightAlpha) }")
    w("    var dark: Color { wbTokenColor(darkRGB, darkAlpha) }")
    w("")
    w("    func resolved(for scheme: ColorScheme) -> Color { scheme == .dark ? dark : light }")
    w("")
    w("    var color: Color {")
    w("        Color(nsColor: NSColor(name: nil) { appearance in")
    w("            let isDark = appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua")
    w("            return isDark ? wbTokenNSColor(darkRGB, darkAlpha) : wbTokenNSColor(lightRGB, lightAlpha)")
    w("        })")
    w("    }")
    w("}")
    w("")
    w("private func wbTokenNSColor(_ rgb: UInt32, _ alpha: Double) -> NSColor {")
    w("    NSColor(srgbRed: CGFloat((rgb >> 16) & 0xff) / 255.0,")
    w("            green: CGFloat((rgb >> 8) & 0xff) / 255.0,")
    w("            blue: CGFloat(rgb & 0xff) / 255.0,")
    w("            alpha: CGFloat(alpha))")
    w("}")
    w("")
    w("private func wbTokenColor(_ rgb: UInt32, _ alpha: Double) -> Color {")
    w("    Color(nsColor: wbTokenNSColor(rgb, alpha))")
    w("}")
    w("")
    w("// MARK: - Colours")
    w("")
    w(f"/// {len(tf.themed)} colour tokens, light and dark. Semantic use goes through")
    w("/// `WbColor`/`WbStatus` (Center/DesignTokens.swift); this layer is the data.")
