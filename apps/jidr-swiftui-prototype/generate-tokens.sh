# SVG -> SwiftUI Path snippet (minimal, documented fallback)
# ---------------------------------------------------------------------------

PATH_TOKEN = re.compile(r"[A-Za-z]|-?\d*\.?\d+(?:[eE][-+]?\d+)?")
SIMPLE_SVG_COMMANDS = set("MmLlHhVvCcSsQqTtZz")


def svg_commands(data: str) -> list[tuple[str, list[float]]]:
    """Tokenise an SVG `d` attribute into (command, numbers) groups."""
    groups: list[tuple[str, list[float]]] = []
    current: tuple[str, list[float]] | None = None
    for token in PATH_TOKEN.findall(data):
        if token.isalpha():
            if len(token) != 1:
                fail(f"SVG path: bad command {token!r}")
            current = (token, [])
            groups.append(current)
        else:
            if current is None:
                fail("SVG path: number before the first command")
            current[1].append(float(token))
    return groups


def svg_path_swift(data: str) -> tuple[list[str], set[str]]:
    """Translate the simple SVG subset (M/L/H/V/C/S/Q/T/Z) into SwiftUI Path calls.

    Returns (lines, unsupported command letters). Arcs are reported, not faked.
    """
    lines: list[str] = []
    unsupported: set[str] = set()
    cx = cy = 0.0
    start = (0.0, 0.0)
    last_cubic: tuple[float, float] | None = None
    last_quad: tuple[float, float] | None = None
    for command, numbers in svg_commands(data):
        letter = command
        upper = letter.upper()
        relative = letter.islower()
        if upper not in "MLHVCSQTZ":
            unsupported.add(letter)
            continue
        args = list(numbers)

        def point(x: float, y: float) -> tuple[float, float]:
            return (cx + x, cy + y) if relative else (x, y)

        def emit_point(name: str, x: float, y: float) -> None:
            lines.append(f"        path.{name}(to: p({x:g}, {y:g}))")

        if upper == "M":
            if len(args) < 2:
                continue
            x, y = point(args[0], args[1])
            lines.append(f"        path.move(to: p({x:g}, {y:g}))")
            cx, cy = x, y
            start = (cx, cy)
            args = args[2:]
            while len(args) >= 2:
                x, y = point(args[0], args[1])
                emit_point("addLine", x, y)
                cx, cy = x, y
                args = args[2:]
            last_cubic = last_quad = None
        elif upper == "L":
            for index in range(0, len(args) - 1, 2):
                x, y = point(args[index], args[index + 1])
                emit_point("addLine", x, y)
                cx, cy = x, y
            last_cubic = last_quad = None
        elif upper == "H":
            for value in args:
                x = cx + value if relative else value
                emit_point("addLine", x, cy)
                cx = x
            last_cubic = last_quad = None
        elif upper == "V":
            for value in args:
                y = cy + value if relative else value
                emit_point("addLine", cx, y)
                cy = y
            last_cubic = last_quad = None
        elif upper == "C":
            for index in range(0, len(args) - 5, 6):
                x1, y1 = point(args[index], args[index + 1])
                x2, y2 = point(args[index + 2], args[index + 3])
                x, y = point(args[index + 4], args[index + 5])
                lines.append(f"        path.addCurve(to: p({x:g}, {y:g}), control1: p({x1:g}, {y1:g}), control2: p({x2:g}, {y2:g}))")
                last_cubic = (x2, y2)
                cx, cy = x, y
            last_quad = None
        elif upper == "S":
            for index in range(0, len(args) - 3, 4):
                if last_cubic is None:
                    x1, y1 = cx, cy
                else:
                    x1, y1 = 2 * cx - last_cubic[0], 2 * cy - last_cubic[1]
                x2, y2 = point(args[index], args[index + 1])
                x, y = point(args[index + 2], args[index + 3])
                lines.append(f"        path.addCurve(to: p({x:g}, {y:g}), control1: p({x1:g}, {y1:g}), control2: p({x2:g}, {y2:g}))")
                last_cubic = (x2, y2)
                cx, cy = x, y
            last_quad = None
        elif upper == "Q":
            for index in range(0, len(args) - 3, 4):
                x1, y1 = point(args[index], args[index + 1])
                x, y = point(args[index + 2], args[index + 3])
                lines.append(f"        path.addQuadCurve(to: p({x:g}, {y:g}), control: p({x1:g}, {y1:g}))")
                last_quad = (x1, y1)
                cx, cy = x, y
            last_cubic = None
        elif upper == "T":
            for index in range(0, len(args) - 1, 2):
                if last_quad is None:
                    x1, y1 = cx, cy
                else:
                    x1, y1 = 2 * cx - last_quad[0], 2 * cy - last_quad[1]
                x, y = point(args[index], args[index + 1])
                lines.append(f"        path.addQuadCurve(to: p({x:g}, {y:g}), control: p({x1:g}, {y1:g}))")
                last_quad = (x1, y1)
                cx, cy = x, y
            last_cubic = None
        elif upper == "Z":
            lines.append("        path.closeSubpath()")
            cx, cy = start
            last_cubic = last_quad = None
    return lines, unsupported


def icon_snippet(svg_path: Path) -> str:
    if not svg_path.exists():
        fail(f"--icon-snippet: no such SVG: {svg_path}")
    text = svg_path.read_text()
    viewbox = re.search(r'viewBox="([^"]+)"', text)
    size = 24.0
    if viewbox:
        parts = [float(part) for part in viewbox.group(1).split()]
        if len(parts) == 4 and parts[2] > 0:
            size = parts[2]
    paths = re.findall(r"<path[^>]*\sd=\"([^\"]+)\"", text)
    if not paths:
        fail(f"--icon-snippet: no <path> in {svg_path}")
    name = camel(svg_path.stem)
    body: list[str] = []
    unsupported: set[str] = set()
    for index, data in enumerate(paths):
        path_commands = {token for token in PATH_TOKEN.findall(data) if token.isalpha()}
        path_unsupported = {letter for letter in path_commands if letter not in SIMPLE_SVG_COMMANDS}
        unsupported |= path_unsupported
        body.append(f"        // d=\"{data}\"")
        if path_unsupported:
            letters = " ".join(sorted(path_unsupported))
            body.append(f"        // skipped: uses unsupported command(s) {letters}")
            continue
        path_lines, _ = svg_path_swift(data)
        body.extend(path_lines)
    lines = [
        "// Minimal SVG -> SwiftUI Path snippet, generated by generate-tokens.sh --icon-snippet.",
        f"// Source: {svg_path.name} ({size:g}x{size:g} viewBox, Lucide ISC).",
        "// Paste into a Shape; stroke it with:",
        "//   .stroke(style: StrokeStyle(lineWidth: WbIcon.iconStroke, lineCap: .round, lineJoin: .round))",
        "// Supported commands: M/m L/l H/h V/v C/c S/s Q/q T/t Z/z.",
    ]
    if unsupported:
        letters = " ".join(sorted(unsupported))
        lines.append(f"// Unsupported commands here ({letters}): A/a arcs need endpoint-to-centre")
        lines.append("// parameterisation (Path.addArc) or a cubic approximation; absent that, keep the")
        lines.append("// SF Symbol for this icon instead of a Path.")
    lines += [
        "// This snippet is evidence for the documented fallback; it is not part of the build.",
        "",
        "import SwiftUI",
        "",
        f"struct WbIconSample_{name}: Shape {{",
        "    func path(in rect: CGRect) -> Path {",
        "        var path = Path()",
        f"        let scale = min(rect.width, rect.height) / {size:g}",
        "        let ox = rect.minX, oy = rect.minY",
        "        func p(_ x: CGFloat, _ y: CGFloat) -> CGPoint {",
        "            CGPoint(x: ox + x * scale, y: oy + y * scale)",
        "        }",
    ]
    lines.extend(body)
    lines += [
        "        return path",
        "    }",
        "}",
    ]
    return "\n".join(lines) + "\n"


