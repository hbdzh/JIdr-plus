@dataclass(frozen=True)
class ColorValue:
    rgb: int
    alpha: float

    def swift(self) -> str:
        if abs(self.alpha - 1.0) < 1e-9:
            return f"0x{self.rgb:06x}"
        return f"0x{self.rgb:06x}, alpha: {self.alpha:g}"


def swift_pair(light: ColorValue, dark: ColorValue) -> str:
    """Swift source for a JidrColorPair, choosing the shortest valid initialiser."""
    if abs(light.alpha - 1.0) < 1e-9 and abs(dark.alpha - 1.0) < 1e-9:
        return f"JidrColorPair(light: 0x{light.rgb:06x}, dark: 0x{dark.rgb:06x})"
    return (
        f"JidrColorPair(light: 0x{light.rgb:06x}, lightAlpha: {light.alpha:g}, "
        f"dark: 0x{dark.rgb:06x}, darkAlpha: {dark.alpha:g})"
    )


def camel(segment: str) -> str:
    parts = [p for p in re.split(r"[-_]", segment) if p]
    if not parts:
        return ""
    out = parts[0]
    for part in parts[1:]:
        out += part[:1].upper() + part[1:]
    return out


def color_name(token: str) -> str:
    """jidr-color-surface-base -> surfaceBase; status/logcat keep their path."""
    name = token[len("jidr-"):] if token.startswith("jidr-") else token
    if name.startswith("color-"):
        name = name[len("color-"):]
    return camel(name)


