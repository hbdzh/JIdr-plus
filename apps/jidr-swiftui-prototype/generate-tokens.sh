#!/bin/bash
# Generate the SwiftUI design-token files from docs/design/tokens.json (D41 single source).
#
# Outputs (each starts with a generated-file header):
#   Sources/DesignTokenData.swift - raw token layer: every colour pair (light/dark),
#                                 spacing, radii, borders, icon/control sizes, frames,
#                                 density, layout, durations/easings/motion, shadows and
#                                 typography styles. Shared by the player and the center.
#   Center/DesignTokens.swift     - semantic Workbench layer on top of the raw layer
#                                 (WbColor/WbStatus/WbSpace/WbRadius/WbType/WbMotion/
#                                 WbShadow) plus the Lucide -> SF Symbol mapping table.
#
# Both outputs are compiled into the same Swift module (build-center.sh globs
# Sources/*.swift and Center/*.swift), and swiftc rejects two files with the same
# basename ("filename used twice"), so the raw layer is Sources/DesignTokenData.swift
# rather than a second DesignTokens.swift. Center/DesignTokens.swift keeps the name
# the semantic layer is referenced by.
#
# Idempotent: identical output is not rewritten; `--check` verifies the checked-in
# files are up to date without writing (exit 1 + diff summary when stale).
#
# Usage:
#   bash apps/jidr-swiftui-prototype/generate-tokens.sh                 # generate
#   bash apps/jidr-swiftui-prototype/generate-tokens.sh --check         # CI check
#   bash apps/jidr-swiftui-prototype/generate-tokens.sh --icon-snippet  # demo SVG -> Path
#
# The script needs python3 (standard library only). It never edits tracked files
# other than the two generated Swift files.
set -euo pipefail

if ! command -v python3 >/dev/null 2>&1; then
  echo "generate-tokens: python3 is required" >&2
  exit 2
fi

root="$(cd "$(dirname "$0")/../.." && pwd)"

exec python3 - "$root" "$@" <<'PYTHON'
