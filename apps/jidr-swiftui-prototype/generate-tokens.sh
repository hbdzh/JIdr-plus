def write_if_changed(path: Path, content: str, check: bool) -> bool:
    content = content.rstrip("\n") + "\n"
    existing = path.read_text() if path.exists() else None
    if existing == content:
        print(f"generate-tokens: unchanged {path.relative_to(ROOT)}")
        return False
    if check:
        print(f"generate-tokens: STALE {path.relative_to(ROOT)} (run generate-tokens.sh)", file=sys.stderr)
        return True
    path.write_text(content)
    print(f"generate-tokens: wrote {path.relative_to(ROOT)} ({len(content.splitlines())} lines)")
    return True


def main(argv: list[str]) -> int:
    check = False
    icon: str | None = None
    index = 0
    while index < len(argv):
        argument = argv[index]
        if argument == "--check":
            check = True
        elif argument == "--icon-snippet":
            index += 1
            if index >= len(argv):
                fail("--icon-snippet needs an SVG path")
            icon = argv[index]
        elif argument in ("-h", "--help"):
            print(__doc__)
            return 0
        else:
            fail(f"unknown argument {argument}; usage: generate-tokens.sh [--check] [--icon-snippet SVG]")
        index += 1

    if icon is not None:
        target = Path(icon)
        if not target.is_absolute():
            target = ROOT / target
        sys.stdout.write(icon_snippet(target))
        return 0

    if not TOKENS_PATH.exists():
        fail(f"missing design tokens: {TOKENS_PATH}")
    try:
        data = json.loads(TOKENS_PATH.read_text())
    except json.JSONDecodeError as error:
        fail(f"tokens.json is not valid JSON: {error}")
    tf = TokenFile(data)
    reduced = reduced_motion(REDUCED_CSS_PATH)

    raw = render_raw(tf, reduced)
    semantic = render_semantic(tf)

    stale = False
    stale |= write_if_changed(SOURCES_OUT, raw, check)
    stale |= write_if_changed(CENTER_OUT, semantic, check)
    if check and stale:
        return 1
    print(
        f"generate-tokens: {len(tf.themed)} colour tokens, "
        f"{len(tf.plain('spacing'))} space, {len(tf.plain('radius'))} radius, "
        f"{len(tf.typography())} type styles, {len(tf.plain('duration'))} durations"
    )
    return 0


sys.exit(main(sys.argv[2:]))
