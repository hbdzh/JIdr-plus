        light, dark = tf.color(token)
        w(f"    static let {color_name(token)} = {swift_pair(light, dark)}")
    w("}")
    w("")

    def scalar_group(enum_name: str, group: str, names: dict[str, str], kind: str, swift_type: str) -> None:
