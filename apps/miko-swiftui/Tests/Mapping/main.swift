import Foundation

let dir = FileManager.default.temporaryDirectory.appendingPathComponent("miko-mapping-test-\(UUID().uuidString)")
try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
defer { try? FileManager.default.removeItem(at: dir) }
let path = dir.appendingPathComponent("device.json")
let store = KeyMappingStore()
store.load(path: path.path)
precondition(store.begin())
precondition(!store.hasUnsavedChanges)
store.place(x: 0.3, y: 0.7, rotation: 0)
precondition(store.pendingPoint == MappingPoint(x: 0.3, y: 0.7, rotation: 0))
precondition(!store.assign("INVALID"))
precondition(!store.assign("a"))
precondition(MappingKey.normalize(keyCode: 48, charactersIgnoringModifiers: "\t") == "TAB")
precondition(MappingKey.normalize(keyCode: 126, charactersIgnoringModifiers: nil) == "UP")
precondition(MappingKey.normalize(keyCode: 43, charactersIgnoringModifiers: ",") == ",")
precondition(store.assign("A"))
precondition(store.pendingPoint == nil)
precondition(store.hasUnsavedChanges)
precondition(store.select(key: "A", rotation: 0))
precondition(store.selectedKey == "A")
precondition(store.move(key: "A", rotation: 0, x: 0.4, y: 0.6))
precondition(store.assign("B"))
precondition(store.draft.bindings == [MappingBinding(key: "B", x: 0.4, y: 0.6, rotation: 0)])
precondition(store.remove(key: "B", rotation: 0))
precondition(store.draft.bindings.isEmpty)
store.place(x: 0.1, y: 0.1, rotation: 0)
precondition(store.assign("W"))
precondition(!store.addJoystick(x: 0.25, y: 0.75, rotation: 0, preset: .wasd))
store.clear(rotation: 0)
precondition(store.addJoystick(x: 0.25, y: 0.75, rotation: 0, preset: .wasd))
precondition(store.resizeJoystick(at: 0, radius: 0.20))
precondition(store.moveJoystick(at: 0, x: 0.30, y: 0.70))
precondition(store.setJoystickPreset(at: 0, preset: .arrows))
precondition(store.draft.joysticks[0].preset == .arrows)
let diag = store.draft.joysticks[0].target(for: [.up, .right], aspectWidthOverHeight: 1.0)
precondition(abs(diag.x - (0.30 + 0.20 / sqrt(2.0))) < 1e-6)
precondition(abs(diag.y - (0.70 - 0.20 / sqrt(2.0))) < 1e-6)
precondition(store.removeJoystick(at: 0))
precondition(store.draft.isEmpty)
store.place(x: 0.3, y: 0.7, rotation: 0)
precondition(store.assign("A"))
store.place(x: 0.2, y: 0.8, rotation: 1)
precondition(store.assign("TAB"))
store.clear(rotation: 0)
precondition(store.draft.bindings == [MappingBinding(key: "TAB", x: 0.2, y: 0.8, rotation: 1)])
store.clear()
precondition(store.draft.bindings.isEmpty)
store.place(x: 0.3, y: 0.7, rotation: 0)
precondition(store.assign("A"))
try store.save()
precondition(!store.hasUnsavedChanges)
let legacyJSON = Data(#"{"version":1,"bindings":[{"key":"A","x":0.3,"y":0.7,"rotation":0}]}"#.utf8)
let legacyDecoded = try JSONDecoder().decode(MappingScheme.self, from: legacyJSON)
precondition(legacyDecoded.bindings.count == 1 && legacyDecoded.joysticks.isEmpty)
let read = try JSONDecoder().decode(MappingScheme.self, from: Data(contentsOf:path))
precondition(read.bindings == [MappingBinding(key:"A", x:0.3, y:0.7, rotation:0)])
// Multi-profile, template & import/export
precondition(KeyMappingStore.sanitizedProfileName("default") == nil)
precondition(KeyMappingStore.sanitizedProfileName("a/b") == nil)
precondition(store.createProfile(named: "MOBA", duplicateCurrent: false))
precondition(store.activeProfileName == "MOBA" && store.profiles == ["MOBA"])
precondition(store.begin())
store.applyTemplate(.moba, rotation: 0)
precondition(!store.draft.joysticks.isEmpty && !store.draft.bindings.isEmpty)
let exportURL = dir.appendingPathComponent("exported.json")
try store.exportData().write(to: exportURL)
precondition(store.saveAsProfile(named: "ARPG"))
precondition(store.activeProfileName == "ARPG" && store.profiles == ["ARPG", "MOBA"])
let reloaded = KeyMappingStore(); reloaded.load(path: path.path)
precondition(reloaded.activeProfileName == "ARPG" && !reloaded.scheme.joysticks.isEmpty)
precondition(reloaded.renameProfile(from: "MOBA", to: "FPS"))
precondition(reloaded.profiles == ["ARPG", "FPS"])
precondition(reloaded.deleteProfile(named: "ARPG"))
precondition(reloaded.activeProfileName == nil && reloaded.scheme.bindings == read.bindings)
try reloaded.importScheme(from: exportURL)
precondition(reloaded.editing && !reloaded.draft.joysticks.isEmpty)
reloaded.cancel()
precondition(store.selectProfile(nil))
precondition(store.begin())
store.place(x: 0.1, y: 0.2, rotation: 1)
precondition(store.assign("A"))
try Data("external change".utf8).write(to:path)
do { try store.save(); fatalError("external change overwritten") } catch { }
let remaining = try Data(contentsOf:path)
precondition(remaining == Data("external change".utf8))
let broken = KeyMappingStore(); broken.load(path:path.path)
precondition(broken.error != nil && broken.failure == .unreadable && !broken.begin())
precondition(broken.resetCorruptedForEditing())
precondition(broken.editing && broken.hasUnsavedChanges)
broken.cancel()
let diskAfterCancel = try Data(contentsOf: path)
precondition(broken.failure == .unreadable && diskAfterCancel == Data("external change".utf8))
precondition(broken.resetCorruptedForEditing())
broken.place(x: 0.5, y: 0.5, rotation: 0)
precondition(broken.assign("K"))
try broken.save()
precondition(broken.failure == nil && broken.scheme.bindings == [MappingBinding(key: "K", x: 0.5, y: 0.5, rotation: 0)])
let prevOpacity = UserDefaults.standard.object(forKey: "miko.keymap.markerOpacity")
defer {
    if let prevOpacity { UserDefaults.standard.set(prevOpacity, forKey: "miko.keymap.markerOpacity") }
    else { UserDefaults.standard.removeObject(forKey: "miko.keymap.markerOpacity") }
}
broken.markerOpacity = 0.01
precondition(broken.markerOpacity == 0.15)
broken.markerOpacity = 1.5
precondition(broken.markerOpacity == 1.0)
print("KeyMapping tests passed")
